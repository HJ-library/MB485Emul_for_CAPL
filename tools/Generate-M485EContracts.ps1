[CmdletBinding()]
param(
    [ValidateSet('Generate', 'Check')]
    [string]$Mode = 'Generate',
    [string]$RepositoryRoot = '',
    [string]$ErrorCodesPath = '',
    [string]$PublicConstantsPath = '',
    [string]$CppOutputPath = '',
    [string]$CaplOutputPath = ''
)

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'

if ([string]::IsNullOrWhiteSpace($RepositoryRoot)) {
    $RepositoryRoot = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
}

if ([string]::IsNullOrWhiteSpace($ErrorCodesPath)) {
    $ErrorCodesPath = Join-Path $RepositoryRoot 'spec\ErrorCodes.csv'
}
if ([string]::IsNullOrWhiteSpace($PublicConstantsPath)) {
    $PublicConstantsPath = Join-Path $RepositoryRoot 'spec\PublicConstants.csv'
}
if ([string]::IsNullOrWhiteSpace($CppOutputPath)) {
    $CppOutputPath = Join-Path $RepositoryRoot 'generated\cpp\M485E_Contracts.generated.h'
}
if ([string]::IsNullOrWhiteSpace($CaplOutputPath)) {
    $CaplOutputPath = Join-Path $RepositoryRoot 'generated\capl\M485E_Contracts.generated.cin'
}

function Assert-Condition {
    param([bool]$Condition, [string]$Message)
    if (-not $Condition) {
        throw $Message
    }
}

function Import-ContractCsv {
    param([string]$Path, [string[]]$ExpectedHeaders)

    Assert-Condition (Test-Path -LiteralPath $Path -PathType Leaf) "Contract source does not exist: $Path"
    $rows = @(Import-Csv -LiteralPath $Path -Encoding UTF8)
    Assert-Condition ($rows.Count -gt 0) "Contract source has no data rows: $Path"
    $actualHeaders = @($rows[0].PSObject.Properties.Name)
    Assert-Condition (($actualHeaders -join '|') -ceq ($ExpectedHeaders -join '|')) `
        "Contract headers must be exactly '$($ExpectedHeaders -join ',')': $Path"
    return $rows
}

function Convert-ToInt32 {
    param([string]$Text, [string]$Field)
    $value = 0
    Assert-Condition ([int]::TryParse($Text, [Globalization.NumberStyles]::Integer,
            [Globalization.CultureInfo]::InvariantCulture, [ref]$value)) `
        "$Field must be a signed 32-bit decimal integer: '$Text'"
    return $value
}

function Add-Unique {
    param([Collections.Generic.HashSet[string]]$Set, [string]$Value, [string]$Field)
    Assert-Condition (-not [string]::IsNullOrWhiteSpace($Value)) "$Field must not be empty."
    Assert-Condition ($Set.Add($Value)) "Duplicate ${Field}: $Value"
}

$errors = Import-ContractCsv $ErrorCodesPath @('Code', 'Symbol', 'Severity', 'Message_Key', 'Meaning')
$constants = Import-ContractCsv $PublicConstantsPath @('Group', 'Symbol', 'Value', 'Meaning')

$symbolSet = New-Object 'Collections.Generic.HashSet[string]' ([StringComparer]::Ordinal)
$errorCodeSet = New-Object 'Collections.Generic.HashSet[string]' ([StringComparer]::Ordinal)
$messageKeySet = New-Object 'Collections.Generic.HashSet[string]' ([StringComparer]::Ordinal)
$severitySymbols = @{
    'Info' = 'M485E_SEVERITY_INFO'
    'Warning' = 'M485E_SEVERITY_WARNING'
    'Error' = 'M485E_SEVERITY_ERROR'
    'Critical' = 'M485E_SEVERITY_CRITICAL'
}

foreach ($constant in $constants) {
    Assert-Condition (-not [string]::IsNullOrWhiteSpace($constant.Group)) 'Constant Group must not be empty.'
    Assert-Condition ($constant.Symbol -cmatch '^M485E_[A-Z0-9_]+$') "Invalid constant symbol: $($constant.Symbol)"
    Add-Unique $symbolSet $constant.Symbol 'public symbol'
    [void](Convert-ToInt32 $constant.Value "Value for $($constant.Symbol)")
}

foreach ($errorRow in $errors) {
    $code = Convert-ToInt32 $errorRow.Code "Code for $($errorRow.Symbol)"
    Assert-Condition ($code -lt 0 -and $code -gt -8000) "Error code is outside the V1 public ranges: $code"
    Assert-Condition ($errorRow.Symbol -cmatch '^M485E_ERR_[A-Z0-9_]+$') "Invalid error symbol: $($errorRow.Symbol)"
    Assert-Condition ($errorRow.Message_Key -cmatch '^[A-Z][A-Z0-9_]+$') "Invalid Message Key: $($errorRow.Message_Key)"
    Assert-Condition ($severitySymbols.ContainsKey($errorRow.Severity)) "Invalid Severity: $($errorRow.Severity)"
    Assert-Condition (-not [string]::IsNullOrWhiteSpace($errorRow.Meaning)) "Meaning must not be empty: $($errorRow.Symbol)"
    Add-Unique $symbolSet $errorRow.Symbol 'public symbol'
    Add-Unique $errorCodeSet ([string]$code) 'error code'
    Add-Unique $messageKeySet $errorRow.Message_Key 'Message Key'
}

Assert-Condition ($errors.Count -ge 90) "The 90-code Phase 2 baseline must not be removed; found $($errors.Count)."

$cpp = New-Object 'Collections.Generic.List[string]'
$cpp.Add('// Generated by tools/Generate-M485EContracts.ps1. Do not edit.')
$cpp.Add('#pragma once')
$cpp.Add('')
$cpp.Add('#include <array>')
$cpp.Add('#include <cstdint>')
$cpp.Add('')
$cpp.Add('namespace m485e')
$cpp.Add('{')
foreach ($constant in $constants) {
    $cpp.Add("inline constexpr std::int32_t $($constant.Symbol) = $($constant.Value);")
}
$cpp.Add("inline constexpr std::int32_t M485E_ERROR_CODE_COUNT = $($errors.Count);")
$cpp.Add('')
foreach ($errorRow in $errors) {
    $cpp.Add("inline constexpr std::int32_t $($errorRow.Symbol) = $($errorRow.Code);")
}
$cpp.Add('')
$cpp.Add('struct ErrorDefinition')
$cpp.Add('{')
$cpp.Add('  std::int32_t code;')
$cpp.Add('  std::int32_t defaultSeverity;')
$cpp.Add('  const char* symbol;')
$cpp.Add('  const char* messageKey;')
$cpp.Add('};')
$cpp.Add('')
$cpp.Add('inline constexpr std::array<ErrorDefinition, M485E_ERROR_CODE_COUNT> kErrorDefinitions{{')
foreach ($errorRow in $errors) {
    $severitySymbol = $severitySymbols[$errorRow.Severity]
    $cpp.Add("    {$($errorRow.Symbol), $severitySymbol, `"$($errorRow.Symbol)`", `"$($errorRow.Message_Key)`"},")
}
$cpp.Add('}};')
$cpp.Add('}  // namespace m485e')
$cppText = ($cpp -join "`n") + "`n"

$capl = New-Object 'Collections.Generic.List[string]'
$capl.Add('/* Generated by tools/Generate-M485EContracts.ps1. Do not edit. */')
$capl.Add('variables')
$capl.Add('{')
foreach ($constant in $constants) {
    $capl.Add("  const long $($constant.Symbol) = $($constant.Value);")
}
$capl.Add("  const long M485E_ERROR_CODE_COUNT = $($errors.Count);")
$capl.Add('')
foreach ($errorRow in $errors) {
    $capl.Add("  const long $($errorRow.Symbol) = $($errorRow.Code); // $($errorRow.Message_Key)")
}
$capl.Add('')
foreach ($errorRow in $errors) {
    $messageSymbol = $errorRow.Symbol.Replace('M485E_ERR_', 'M485E_MESSAGE_KEY_')
    $messageLength = $errorRow.Message_Key.Length + 1
    $capl.Add("  char $messageSymbol`[$messageLength`] = `"$($errorRow.Message_Key)`";")
}
$capl.Add('}')
$caplText = ($capl -join "`n") + "`n"

function Write-OrCheckGeneratedFile {
    param([string]$Path, [string]$Content)

    if ($Mode -eq 'Check') {
        Assert-Condition (Test-Path -LiteralPath $Path -PathType Leaf) "Generated file is missing: $Path"
        $actual = [IO.File]::ReadAllText($Path, [Text.Encoding]::UTF8)
        Assert-Condition ($actual -ceq $Content) "Generated file is stale: $Path"
        return
    }

    $parent = Split-Path -Parent $Path
    if (-not (Test-Path -LiteralPath $parent)) {
        [void](New-Item -ItemType Directory -Path $parent -Force)
    }
    [IO.File]::WriteAllText($Path, $Content, (New-Object Text.UTF8Encoding($false)))
}

Write-OrCheckGeneratedFile $CppOutputPath $cppText
Write-OrCheckGeneratedFile $CaplOutputPath $caplText
Write-Host "M485E contract generation $Mode completed: $($errors.Count) errors, $($constants.Count) public constants."
